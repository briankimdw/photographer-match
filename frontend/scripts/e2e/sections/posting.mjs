export const listing = {
  id: 'listing',
  title: 'A second listing in another vertical',
  roles: ['caterer', 'clientA', 'clientB'],
  steps: [
    {
      name: 'becomeProvider in a concurrent vertical (max_concurrent)',
      run: async (ctx) => {
        const { app, state } = ctx
        const me = await ctx.as('caterer')
        const mine = await app.portfolio.getMyProviders(me.uid)
        const slug = `e2e-${ctx.roles.caterer.username.replace(/[^a-z0-9]+/gi, '-')}-2nd`.toLowerCase()
        let row = mine.find((p) => p.slug === slug)
        let vertical
        if (row) {
          vertical = row.vertical
          await me.client.from('providers').update({ status: 'active' }).eq('id', row.id) // reuse the one an earlier run made
        } else {
          const taken = new Set(mine.map((p) => p.vertical))
          const pick = app.verticals.VERTICALS.find((v) => v.concurrent && !taken.has(v.slug) && v.slug === 'rentals') || app.verticals.VERTICALS.find((v) => v.concurrent && !taken.has(v.slug))
          if (!pick) skip('the caterer already has a listing in every concurrent vertical')
          vertical = pick.slug
          const services = await app.portfolio.getServicesOf(vertical)
          row = await app.portfolio.becomeProvider({ displayName: `[e2e] ${ctx.roles.caterer.user.business || 'Vendor'} ${pick.name}`, slug, city: 'Los Angeles, CA', vertical, serviceIds: services.slice(0, 1).map((s) => s.id), bio: ctx.tag('second listing') })
        }
        ctx.cleanup.leave('providers', row.id)
        ctx.cleanup.add('listing', `hide listing ${slug}`, async () => {
          const c = await ctx.as('caterer')
          await c.client.from('providers').update({ status: 'draft' }).eq('id', row.id)
        })
        const fresh = await app.portfolio.getMyProvider(me.uid, vertical)
        eq(fresh.id, row.id, 'getMyProvider(uid, vertical)')
        eq(fresh.status, 'active', 'status')
        assert(fresh.max_concurrent > 1, `max_concurrent ${fresh.max_concurrent}, expected > 1 for ${vertical}`)
        state.second = { id: row.id, vertical, slug, maxConcurrent: fresh.max_concurrent }
        return `${vertical} listing ${slug} (max_concurrent ${fresh.max_concurrent}); caterer now has ${(await app.portfolio.getMyProviders(me.uid)).length} listings`
      },
    },
    {
      name: 'add a per-item package with min/max',
      run: async (ctx) => {
        const { app, state } = ctx
        await ctx.as('caterer')
        const services = await app.portfolio.getServicesOf(state.second.vertical)
        const pkg = await app.provider.createPackage(state.second.id, { name: '[e2e] Chair rental', categoryId: services[0]?.id ?? null, priceType: 'per_item', price: 8, depositPct: 25, attributes: { min_quantity: 10, max_quantity: 500 } })
        ctx.cleanup.add('content', `delete package ${pkg.id.slice(0, 8)}`, async () => {
          const c = await ctx.as('caterer')
          await c.client.from('packages').delete().eq('id', pkg.id)
        })
        eq(pkg.priceType, 'per_item', 'price type')
        eq(pkg.price, 8, 'price')
        eq(pkg.minQuantity, 10, 'min quantity')
        eq(pkg.maxQuantity, 500, 'max quantity')
        state.second.pkg = pkg
        return `"${pkg.name}" $8 each, 10-500`
      },
    },
    {
      name: 'public: listed in its vertical and in date search',
      run: async (ctx) => {
        const { app, state } = ctx
        ctx.anon()
        const list = await app.catalog.listProviders({ vertical: state.second.vertical })
        const p = list.find((x) => x.id === state.second.id)
        assert(p, `not in listProviders({ vertical: '${state.second.vertical}' })`)
        eq(p.startingPrice, 8, 'starting price')
        const day = ctx.dates.next()
        const found = await app.catalog.searchProviders({ vertical: state.second.vertical, dates: [day] })
        const hit = found.find((x) => x.id === state.second.id)
        assert(hit && hit.freeDates.includes(day), 'not free in date search')
        return `${list.length} ${state.second.vertical} listings; free on ${day}`
      },
    },
    {
      name: 'two overlapping bookings fit (capacity)',
      soft: true,
      run: async (ctx) => {
        const { app, state } = ctx
        const { rows, dates } = await ctx.book('clientA', { packageId: state.second.pkg.id, quantity: 20 }, { label: 'second listing 1' })
        eq(rows[0].total_cents, 16000, 'total for 20 items at $8')
        await ctx.as('clientB')
        const more = await app.bookings.requestBooking({ packageId: state.second.pkg.id, dates, startTime: '10:00', quantity: 12, notes: ctx.tag('second listing 2') })
        ctx.trackBooking('clientB', more[0].id, 'second listing 2')
        await app.bookings.cancelBooking(more[0].id)
        await ctx.as('clientA')
        await app.bookings.cancelBooking(rows[0].id)
        return `both fit on ${dates[0]}; cancelled`
      },
    },
    {
      name: 'hide the listing (draft) -> gone from public lists',
      run: async (ctx) => {
        const { app, state } = ctx
        const me = await ctx.as('caterer')
        const { error } = await me.client.from('providers').update({ status: 'draft' }).eq('id', state.second.id)
        if (error) throw error
        assert((await app.portfolio.getMyProviders(me.uid)).some((p) => p.id === state.second.id), 'owner lost sight of the draft')
        ctx.anon()
        assert(!(await app.catalog.listProviders({ vertical: state.second.vertical })).some((p) => p.id === state.second.id), 'draft still public')
        return 'draft; owner still sees it'
      },
    },
  ],
}
